package hash

import (
	"bytes"
	"fmt"
	"slices"
)

type merkleDamgardHasher struct {
	state []byte
	iv    []byte
	f     Compressor
}

// Write implements hash.Write
func (h *merkleDamgardHasher) Write(p []byte) (n int, err error) {
	blockSize := h.f.BlockSize()
	for len(p) != 0 {
		nWritten := blockSize
		if len(p) < blockSize {
			nWritten = len(p)
			if p, err = cloneLeftPadded(p, blockSize); err != nil {
				panic(err) // this should not be possible
			}
		}
		if h.state, err = h.f.Compress(h.state, p[:blockSize]); err != nil {
			return
		}
		n += nWritten
		p = p[blockSize:]
	}
	return
}

func (h *merkleDamgardHasher) Sum(b []byte) []byte {
	return append(b, h.state...)
}

func (h *merkleDamgardHasher) Reset() {
	h.state = bytes.Clone(h.iv)
}

func (h *merkleDamgardHasher) Size() int {
	return h.f.BlockSize()
}

func (h *merkleDamgardHasher) BlockSize() int {
	return h.f.BlockSize()
}

func (h *merkleDamgardHasher) State() []byte {
	return h.state
}

// SetState sets h's state to state. If len(state) > BlockSize, an error is thrown.
// If len(state) < BlockSize, h's state is set to state, and left padded with zeroes.
// len(state) > BlockSize will result in an error.
func (h *merkleDamgardHasher) SetState(state []byte) error {
	var err error
	h.state, err = cloneLeftPadded(state, h.BlockSize())
	return err
}

// NewMerkleDamgardHasher transforms a 2-1 one-way compression function into a
// hash function using a Merkle-Damgard construction. The resulting hash
// function has a block size equal to the block size of compression function.
//
// NB! The construction does not perform explicit padding on the input data. The
// last block of input data is zero-padded to full block size. This means that
// the construction is not collision resistant for generic data as the digest of
// input and input concatenated with zeros (up to the same number of total
// blocks) is same. For collision resistance the caller should perform explicit
// padding on the input data.
//
// - initialState is provided as initial input to the compression
// function. Its preimage should not be known and thus it should be generated
// using a deterministic method.
// If the given initialState is shorter than the hash block size, it will be zero-padded
// on the left. An oversized initialState will cause a panic.
func NewMerkleDamgardHasher(f Compressor, initialState []byte) StateStorer {
	iv, err := cloneLeftPadded(initialState, f.BlockSize())
	if err != nil {
		panic(err)
	}
	return &merkleDamgardHasher{
		f:     f,
		iv:    iv,
		state: bytes.Clone(iv),
	}
}

// cloneLeftPadded copies b into a new byte slice of size n.
// If len(b) < n, it will be padded on the left.
// len(b) > n will result in an error.
func cloneLeftPadded(b []byte, n int) ([]byte, error) {
	if len(b) > n {
		return nil, fmt.Errorf("state/iv must not exceed the hash block size: %d > %d", len(b), n)
	}
	res := make([]byte, n)
	copy(res[n-len(b):], b)
	return res, nil
}

// FieldMerkleDamgardHasher is a Merkle-Damgard hash function over blocks of
// elements of a field F. It is both a [FieldHasher] over digests of type []F and
// a [StateStorer], whose bytes are the marshalled elements. See
// [NewFieldMerkleDamgardHasher].
type FieldMerkleDamgardHasher[F any, PF interface {
	*F
	SetBytesCanonical([]byte) error
	Marshal() []byte
}] struct {
	f        FieldCompressor[[]F]
	iv       []F
	state    []F
	pending  []F // elements written by WriteField and not compressed yet, fewer than a block
	elemSize int // size of a marshaled element, in bytes
}

// NewFieldMerkleDamgardHasher transforms a 2-1 one-way compression function over
// blocks of field elements into a hash function using a Merkle-Damgard
// construction. Its digest is a block.
//
// NB! The construction does not perform explicit padding on the input data,
// see [NewMerkleDamgardHasher]. A partial last block is padded with zeros on the
// left to a full block, so the digests of an input and of the input preceded by
// zeros in its last block are the same.
//
// A block can be written by several calls to WriteField, see [FieldHasher].
// Write ends the current block, and pads the last block of its input, so the
// digest depends on how the input is split among the calls to Write.
//
// initialState is provided as initial input to the compression function; its
// preimage should not be known, so it should be generated by a deterministic
// method. Its length is the block length, which must be the block length of f.
func NewFieldMerkleDamgardHasher[F any, PF interface {
	*F
	SetBytesCanonical([]byte) error
	Marshal() []byte
}](f FieldCompressor[[]F], initialState []F) *FieldMerkleDamgardHasher[F, PF] {
	blockLen := len(initialState)
	if blockLen == 0 {
		panic("the initial state must not be empty")
	}
	iv := slices.Clone(initialState)

	var e F
	return &FieldMerkleDamgardHasher[F, PF]{
		f:        f,
		iv:       iv,
		state:    slices.Clone(iv),
		pending:  make([]F, 0, blockLen),
		elemSize: len(PF(&e).Marshal()),
	}
}

// WriteField implements [FieldHasher].
func (h *FieldMerkleDamgardHasher[F, PF]) WriteField(e ...F) {
	blockLen := len(h.iv)
	for len(e) != 0 {
		if len(h.pending) == 0 && len(e) >= blockLen {
			h.f.CompressField(h.state, h.state, e[:blockLen])
			e = e[blockLen:]
			continue
		}
		n := min(blockLen-len(h.pending), len(e))
		h.pending = append(h.pending, e[:n]...)
		e = e[n:]
		if len(h.pending) == blockLen {
			h.f.CompressField(h.state, h.state, h.pending)
			h.pending = h.pending[:0]
		}
	}
}

// PadBlock implements [FieldHasher].
func (h *FieldMerkleDamgardHasher[F, PF]) PadBlock() {
	if len(h.pending) != 0 {
		h.f.CompressField(h.state, h.state, h.paddedPending())
		h.pending = h.pending[:0]
	}
}

// SumField implements [FieldHasher].
func (h *FieldMerkleDamgardHasher[F, PF]) SumField() []F {
	if len(h.pending) == 0 {
		return slices.Clone(h.state)
	}
	res := make([]F, len(h.iv))
	h.f.CompressField(res, h.state, h.paddedPending())
	return res
}

func (h *FieldMerkleDamgardHasher[F, PF]) paddedPending() []F {
	block := make([]F, len(h.iv))
	copy(block[len(block)-len(h.pending):], h.pending)
	return block
}

// Write implements hash.Write
func (h *FieldMerkleDamgardHasher[F, PF]) Write(p []byte) (n int, err error) {
	h.PadBlock()
	blockSize := h.BlockSize()
	block := make([]F, len(h.iv))
	for len(p) != 0 {
		chunk := p[:min(len(p), blockSize)]
		if err = h.parseBlock(block, chunk); err != nil {
			return
		}
		h.WriteField(block...)
		n += len(chunk)
		p = p[len(chunk):]
	}
	return
}

func (h *FieldMerkleDamgardHasher[F, PF]) Sum(b []byte) []byte {
	return h.appendMarshalled(b, h.SumField())
}

func (h *FieldMerkleDamgardHasher[F, PF]) Reset() {
	copy(h.state, h.iv)
	h.pending = h.pending[:0]
}

func (h *FieldMerkleDamgardHasher[F, PF]) Size() int {
	return h.BlockSize()
}

func (h *FieldMerkleDamgardHasher[F, PF]) BlockSize() int {
	return len(h.iv) * h.elemSize
}

// State returns the state after the elements written so far, where an incomplete
// block is padded as by PadBlock; it is the digest. If elements of an incomplete
// block are pending, a hasher restored from it by SetState is in the state h
// would be in after PadBlock.
func (h *FieldMerkleDamgardHasher[F, PF]) State() []byte {
	return h.Sum(nil)
}

// SetState sets h's state to state, and discards the elements of an incomplete
// block. If len(state) < BlockSize, h's state is set to state, left padded with zeroes.
// len(state) > BlockSize will result in an error.
func (h *FieldMerkleDamgardHasher[F, PF]) SetState(state []byte) error {
	newState := make([]F, len(h.state))
	if err := h.parseBlock(newState, state); err != nil {
		return err
	}
	h.state = newState
	h.pending = h.pending[:0]
	return nil
}

func (h *FieldMerkleDamgardHasher[F, PF]) appendMarshalled(b []byte, e []F) []byte {
	for i := range e {
		b = append(b, PF(&e[i]).Marshal()...)
	}
	return b
}

// parseBlock parses b, padded with zeros on the left to a block, into the
// elements of dst. It is an error if b is longer than a block.
func (h *FieldMerkleDamgardHasher[F, PF]) parseBlock(dst []F, b []byte) error {
	blockSize := h.BlockSize()
	if len(b) > blockSize {
		return fmt.Errorf("state/iv must not exceed the hash block size: %d > %d", len(b), blockSize)
	}
	if len(b) < blockSize {
		padded := make([]byte, blockSize)
		copy(padded[blockSize-len(b):], b)
		b = padded
	}
	for i := range dst {
		if err := PF(&dst[i]).SetBytesCanonical(b[i*h.elemSize : (i+1)*h.elemSize]); err != nil {
			return err
		}
	}
	return nil
}
