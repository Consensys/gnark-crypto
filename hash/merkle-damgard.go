package hash

import (
	"bytes"
	"fmt"
)

type merkleDamgardHasher struct {
	state []byte
	iv    []byte
	f     Compressor
}

// Write implements hash.Write
func (h *merkleDamgardHasher) Write(p []byte) (n int, err error) {
	blockSize := h.f.BlockSize()
	for len(p) != 0 {
		nWritten := blockSize
		if len(p) < blockSize {
			nWritten = len(p)
			if p, err = cloneLeftPadded(p, blockSize); err != nil {
				panic(err) // this should not be possible
			}
		}
		if h.state, err = h.f.Compress(h.state, p[:blockSize]); err != nil {
			return
		}
		n += nWritten
		p = p[blockSize:]
	}
	return
}

func (h *merkleDamgardHasher) Sum(b []byte) []byte {
	return append(b, h.state...)
}

func (h *merkleDamgardHasher) Reset() {
	h.state = bytes.Clone(h.iv)
}

func (h *merkleDamgardHasher) Size() int {
	return h.f.BlockSize()
}

func (h *merkleDamgardHasher) BlockSize() int {
	return h.f.BlockSize()
}

func (h *merkleDamgardHasher) State() []byte {
	return h.state
}

// SetState sets h's state to state. If len(state) > BlockSize, an error is thrown.
// If len(state) < BlockSize, h's state is set to state, and left padded with zeroes.
// len(state) > BlockSize will result in an error.
func (h *merkleDamgardHasher) SetState(state []byte) error {
	var err error
	h.state, err = cloneLeftPadded(state, h.BlockSize())
	return err
}

// NewMerkleDamgardHasher transforms a 2-1 one-way compression function into a
// hash function using a Merkle-Damgard construction. The resulting hash
// function has a block size equal to the block size of compression function.
//
// NB! The construction does not perform explicit padding on the input data. The
// last block of input data is zero-padded to full block size. This means that
// the construction is not collision resistant for generic data as the digest of
// input and input concatenated with zeros (up to the same number of total
// blocks) is same. For collision resistance the caller should perform explicit
// padding on the input data.
//
// - initialState is provided as initial input to the compression
// function. Its preimage should not be known and thus it should be generated
// using a deterministic method.
// If the given initialState is shorter than the hash block size, it will be zero-padded
// on the left. An oversized initialState will cause a panic.
func NewMerkleDamgardHasher(f Compressor, initialState []byte) StateStorer {
	iv, err := cloneLeftPadded(initialState, f.BlockSize())
	if err != nil {
		panic(err)
	}
	return &merkleDamgardHasher{
		f:     f,
		iv:    iv,
		state: bytes.Clone(iv),
	}
}

// cloneLeftPadded copies b into a new byte slice of size n.
// If len(b) < n, it will be padded on the left.
// len(b) > n will result in an error.
func cloneLeftPadded(b []byte, n int) ([]byte, error) {
	if len(b) > n {
		return nil, fmt.Errorf("state/iv must not exceed the hash block size: %d > %d", len(b), n)
	}
	res := make([]byte, n)
	copy(res[n-len(b):], b)
	return res, nil
}

// FieldMerkleDamgardHasher is a Merkle-Damgard hash function over blocks of
// elements of a field F. It is a [FieldHasher] over digests of type D. See
// [NewFieldMerkleDamgardHasher].
type FieldMerkleDamgardHasher[F any, D Block[F]] struct {
	f     FieldCompressor[D]
	iv    D
	state D
	buf   D   // elements written by WriteElement and not compressed yet, fewer than a block
	n     int // number of pending elements in buf

	scratch D // the padded block being compressed, held here rather than in a local variable so that it does not escape to the heap
}

// NewFieldMerkleDamgardHasher transforms a 2-1 one-way compression function over
// blocks of field elements into a hash function using a Merkle-Damgard
// construction. Its digest is a block.
//
// NB! The construction does not perform explicit padding on the input data,
// see [NewMerkleDamgardHasher]. A partial last block is padded with zeros on the
// left to a full block, so the digests of an input and of the input preceded by
// zeros in its last block are the same.
//
// A block can be written by several calls to WriteElements, see [FieldHasher].
//
// initialState is provided as initial input to the compression function; its
// preimage should not be known, so it should be generated by a deterministic
// method. Its type is the block type.
func NewFieldMerkleDamgardHasher[F any, D Block[F]](f FieldCompressor[D], initialState D) *FieldMerkleDamgardHasher[F, D] {
	return &FieldMerkleDamgardHasher[F, D]{
		f:     f,
		iv:    initialState,
		state: initialState,
	}
}

// WriteElement implements [FieldHasher].
func (h *FieldMerkleDamgardHasher[F, D]) WriteElement(e F) {
	h.buf[h.n] = e
	h.n++
	if h.n == len(h.buf) {
		h.f.CompressField(&h.state, &h.state, &h.buf)
		h.n = 0
	}
}

// WriteElements implements [FieldHasher].
func (h *FieldMerkleDamgardHasher[F, D]) WriteElements(e ...F) {
	for i := range e {
		h.WriteElement(e[i])
	}
}

// PadBlock implements [FieldHasher].
func (h *FieldMerkleDamgardHasher[F, D]) PadBlock() {
	if h.n != 0 {
		h.scratch = h.paddedPending()
		h.f.CompressField(&h.state, &h.state, &h.scratch)
		h.n = 0
	}
}

// SumElement implements [FieldHasher].
func (h *FieldMerkleDamgardHasher[F, D]) SumElement() D {
	if h.n == 0 {
		return h.state
	}
	h.scratch = h.paddedPending()
	h.f.CompressField(&h.scratch, &h.state, &h.scratch)
	return h.scratch
}

func (h *FieldMerkleDamgardHasher[F, D]) paddedPending() D {
	var block D
	for i := range h.n {
		block[len(block)-h.n+i] = h.buf[i]
	}
	return block
}

// BlockLen implements [FieldHasher].
func (h *FieldMerkleDamgardHasher[F, D]) BlockLen() int {
	return len(h.buf)
}

// Reset implements [FieldHasher].
func (h *FieldMerkleDamgardHasher[F, D]) Reset() {
	h.state = h.iv
	h.n = 0
}

// FieldMerkleDamgardByteHasher hashes bytes with a [FieldMerkleDamgardHasher].
// It is a [StateStorer], whose bytes are the marshalled elements of a block, over
// a field hasher it owns. Write pads the last block of its input, so the digest
// depends on how the input is split among the calls to Write. See
// [NewFieldMerkleDamgardByteHasher].
type FieldMerkleDamgardByteHasher[F any, PF interface {
	*F
	SetBytesCanonical([]byte) error
	Marshal() []byte
}, D Block[F]] struct {
	hasher   *FieldMerkleDamgardHasher[F, D]
	elemSize int // size of a marshaled element, in bytes
}

// NewFieldMerkleDamgardByteHasher returns a byte hasher over h, which it owns.
func NewFieldMerkleDamgardByteHasher[F any, PF interface {
	*F
	SetBytesCanonical([]byte) error
	Marshal() []byte
}, D Block[F]](h *FieldMerkleDamgardHasher[F, D]) *FieldMerkleDamgardByteHasher[F, PF, D] {
	var e F
	return &FieldMerkleDamgardByteHasher[F, PF, D]{hasher: h, elemSize: len(PF(&e).Marshal())}
}

// Write implements hash.Write
func (h *FieldMerkleDamgardByteHasher[F, PF, D]) Write(p []byte) (n int, err error) {
	h.hasher.PadBlock()
	blockSize := h.BlockSize()
	var block D
	for len(p) != 0 {
		chunk := p[:min(len(p), blockSize)]
		if err = h.parseBlock(&block, chunk); err != nil {
			return
		}
		for i := range len(block) {
			h.hasher.WriteElement(block[i])
		}
		n += len(chunk)
		p = p[len(chunk):]
	}
	return
}

func (h *FieldMerkleDamgardByteHasher[F, PF, D]) Sum(b []byte) []byte {
	return h.appendMarshalled(b, h.hasher.SumElement())
}

func (h *FieldMerkleDamgardByteHasher[F, PF, D]) Reset() {
	h.hasher.Reset()
}

func (h *FieldMerkleDamgardByteHasher[F, PF, D]) Size() int {
	return h.BlockSize()
}

func (h *FieldMerkleDamgardByteHasher[F, PF, D]) BlockSize() int {
	return h.hasher.BlockLen() * h.elemSize
}

// State returns the marshalled state, which is the digest.
func (h *FieldMerkleDamgardByteHasher[F, PF, D]) State() []byte {
	return h.Sum(nil)
}

// SetState sets h's state to state. If len(state) < BlockSize, h's state is set
// to state, left padded with zeroes.
// len(state) > BlockSize will result in an error.
func (h *FieldMerkleDamgardByteHasher[F, PF, D]) SetState(state []byte) error {
	var newState D
	if err := h.parseBlock(&newState, state); err != nil {
		return err
	}
	h.hasher.state = newState
	h.hasher.n = 0
	return nil
}

func (h *FieldMerkleDamgardByteHasher[F, PF, D]) appendMarshalled(b []byte, e D) []byte {
	for i := range len(e) {
		b = append(b, PF(&e[i]).Marshal()...)
	}
	return b
}

// parseBlock parses b, padded with zeros on the left to a block, into the
// elements of dst. It is an error if b is longer than a block.
func (h *FieldMerkleDamgardByteHasher[F, PF, D]) parseBlock(dst *D, b []byte) error {
	blockSize := h.BlockSize()
	if len(b) > blockSize {
		return fmt.Errorf("state/iv must not exceed the hash block size: %d > %d", len(b), blockSize)
	}
	if len(b) < blockSize {
		padded := make([]byte, blockSize)
		copy(padded[blockSize-len(b):], b)
		b = padded
	}
	for i := range len(*dst) {
		if err := PF(&(*dst)[i]).SetBytesCanonical(b[i*h.elemSize : (i+1)*h.elemSize]); err != nil {
			return err
		}
	}
	return nil
}

// LargeFieldMerkleDamgardHasher is a Merkle-Damgard hash function over elements
// of a field F large enough for one element to be a block and a digest. It is a
// [FieldHasher] over digests of type F. See [NewLargeFieldMerkleDamgardHasher].
type LargeFieldMerkleDamgardHasher[F any] struct {
	f     FieldCompressor[F]
	iv    F
	state F
	block F // the element being compressed, held here rather than in a local variable so that it does not escape to the heap
}

// NewLargeFieldMerkleDamgardHasher transforms a 2-1 one-way compression
// function over field elements into a hash function using a Merkle-Damgard
// construction. Each element is a block, and the digest is an element.
//
// NB! The construction does not perform explicit padding on the input data,
// see [NewMerkleDamgardHasher].
//
// initialState is provided as initial input to the compression function; its
// preimage should not be known, so it should be generated by a deterministic
// method.
func NewLargeFieldMerkleDamgardHasher[F any](f FieldCompressor[F], initialState F) *LargeFieldMerkleDamgardHasher[F] {
	return &LargeFieldMerkleDamgardHasher[F]{
		f:     f,
		iv:    initialState,
		state: initialState,
	}
}

// WriteElement implements [FieldHasher].
func (h *LargeFieldMerkleDamgardHasher[F]) WriteElement(e F) {
	h.block = e
	h.f.CompressField(&h.state, &h.state, &h.block)
}

// WriteElements implements [FieldHasher].
func (h *LargeFieldMerkleDamgardHasher[F]) WriteElements(e ...F) {
	for i := range e {
		h.WriteElement(e[i])
	}
}

// PadBlock implements [FieldHasher]. A block is an element, so there is never an
// incomplete block, and PadBlock does nothing.
func (h *LargeFieldMerkleDamgardHasher[F]) PadBlock() {}

// SumElement implements [FieldHasher].
func (h *LargeFieldMerkleDamgardHasher[F]) SumElement() F {
	return h.state
}

// BlockLen implements [FieldHasher].
func (h *LargeFieldMerkleDamgardHasher[F]) BlockLen() int {
	return 1
}

// Reset implements [FieldHasher].
func (h *LargeFieldMerkleDamgardHasher[F]) Reset() {
	h.state = h.iv
}

// LargeFieldMerkleDamgardByteHasher hashes bytes with a
// [LargeFieldMerkleDamgardHasher]. It is a [StateStorer], whose bytes are the
// marshalled elements of a block, over a field hasher it owns. Write pads a
// partial last element of its input with zeros on the left, so the digests of an
// input and of the input preceded by zeros in its last element are the same. See
// [NewLargeFieldMerkleDamgardByteHasher].
type LargeFieldMerkleDamgardByteHasher[F any, PF interface {
	*F
	SetBytesCanonical([]byte) error
	Marshal() []byte
}] struct {
	hasher   *LargeFieldMerkleDamgardHasher[F]
	block    F   // the element being compressed, held here rather than in a local variable so that it does not escape to the heap
	elemSize int // size of a marshaled element, in bytes
}

// NewLargeFieldMerkleDamgardByteHasher returns a byte hasher over h, which it owns.
func NewLargeFieldMerkleDamgardByteHasher[F any, PF interface {
	*F
	SetBytesCanonical([]byte) error
	Marshal() []byte
}](h *LargeFieldMerkleDamgardHasher[F]) *LargeFieldMerkleDamgardByteHasher[F, PF] {
	var e F
	return &LargeFieldMerkleDamgardByteHasher[F, PF]{hasher: h, elemSize: len(PF(&e).Marshal())}
}

// Write implements hash.Write
func (h *LargeFieldMerkleDamgardByteHasher[F, PF]) Write(p []byte) (n int, err error) {
	for len(p) != 0 {
		chunk := p[:min(len(p), h.elemSize)]
		if err = h.parseElement(&h.block, chunk); err != nil {
			return
		}
		h.hasher.f.CompressField(&h.hasher.state, &h.hasher.state, &h.block)
		n += len(chunk)
		p = p[len(chunk):]
	}
	return
}

func (h *LargeFieldMerkleDamgardByteHasher[F, PF]) Sum(b []byte) []byte {
	return append(b, PF(&h.hasher.state).Marshal()...)
}

func (h *LargeFieldMerkleDamgardByteHasher[F, PF]) Reset() {
	h.hasher.Reset()
}

func (h *LargeFieldMerkleDamgardByteHasher[F, PF]) Size() int {
	return h.elemSize
}

func (h *LargeFieldMerkleDamgardByteHasher[F, PF]) BlockSize() int {
	return h.elemSize
}

// State returns the marshalled state, which is the digest.
func (h *LargeFieldMerkleDamgardByteHasher[F, PF]) State() []byte {
	return h.Sum(nil)
}

// SetState sets h's state to state. If len(state) < BlockSize, it is left padded
// with zeros. A state longer than BlockSize, or not the encoding of a canonical
// element, results in an error.
func (h *LargeFieldMerkleDamgardByteHasher[F, PF]) SetState(state []byte) error {
	var newState F
	if err := h.parseElement(&newState, state); err != nil {
		return err
	}
	h.hasher.state = newState
	return nil
}

// parseElement parses b, padded with zeros on the left to an element, into dst.
// It is an error if b is longer than an element.
func (h *LargeFieldMerkleDamgardByteHasher[F, PF]) parseElement(dst *F, b []byte) error {
	if len(b) > h.elemSize {
		return fmt.Errorf("state/iv must not exceed the hash block size: %d > %d", len(b), h.elemSize)
	}
	if len(b) < h.elemSize {
		padded := make([]byte, h.elemSize)
		copy(padded[h.elemSize-len(b):], b)
		b = padded
	}
	return PF(dst).SetBytesCanonical(b)
}
